const {contextBridge,ipcRenderer}=require('electron');
// Deliberately expose one bounded operation per message, never arbitrary IPC.
contextBridge.exposeInMainWorld('launcher',Object.freeze({
  snapshot:()=>ipcRenderer.invoke('launcher:snapshot'),
  logs:()=>ipcRenderer.invoke('launcher:logs'),
  chooseGame:()=>ipcRenderer.invoke('launcher:choose-game'),
  cancel:()=>ipcRenderer.invoke('launcher:cancel'),
  settings:values=>ipcRenderer.invoke('launcher:settings',values),
  play:()=>ipcRenderer.invoke('launcher:play'),
  newSave:region=>ipcRenderer.invoke('launcher:new-save',region),
  saves:()=>ipcRenderer.invoke('launcher:saves'),
  openSave:id=>ipcRenderer.invoke('launcher:open-save',id),
  cardEntry:index=>ipcRenderer.invoke('launcher:card-entry',index),
  saveCopy:edits=>ipcRenderer.invoke('launcher:save-copy',edits),
  assets:()=>ipcRenderer.invoke('launcher:assets'),
  cars:()=>ipcRenderer.invoke('launcher:cars'),
  tracks:()=>ipcRenderer.invoke('launcher:tracks'),
  previewTrackPart:(id,part)=>ipcRenderer.invoke('launcher:preview-track-part',id,part),
  importTrackPart:(id,part,revision)=>ipcRenderer.invoke('launcher:import-track-part',id,part,revision),
  exportTrackPart:(id,part)=>ipcRenderer.invoke('launcher:export-track-part',id,part),
  importTrackMesh:(id,revision)=>ipcRenderer.invoke('launcher:import-track-mesh',id,revision),
  exportTrackMesh:id=>ipcRenderer.invoke('launcher:export-track-mesh',id),
  trackScene:bank=>ipcRenderer.invoke('launcher:track-scene',bank),
  trackPreview:bank=>ipcRenderer.invoke('launcher:track-preview',bank),
  saveTrackObject:(bank,index,values,revision)=>ipcRenderer.invoke('launcher:save-track-object',bank,index,values,revision),
  saveRoadPoint:(bank,index,values,revision)=>ipcRenderer.invoke('launcher:save-road-point',bank,index,values,revision),
  saveTerrainCell:(bank,index,values,revision)=>ipcRenderer.invoke('launcher:save-terrain-cell',bank,index,values,revision),
  saveRoadArc:(bank,index,values,revision)=>ipcRenderer.invoke('launcher:save-road-arc',bank,index,values,revision),
  exportCarSet:key=>ipcRenderer.invoke('launcher:export-car-set',key),
  importCarSet:key=>ipcRenderer.invoke('launcher:import-car-set',key),
  previewWholeCar:(bank,body,rival,modId)=>ipcRenderer.invoke('launcher:preview-whole-car',bank,body,rival,modId),
  carSpec:bank=>ipcRenderer.invoke('launcher:car-spec',bank),
  saveCarSpec:(bank,edits,revision)=>ipcRenderer.invoke('launcher:save-car-spec',bank,edits,revision),
  previewCar:(key,modId)=>ipcRenderer.invoke('launcher:preview-car',key,modId),
  carMaterials:key=>ipcRenderer.invoke('launcher:car-materials',key),
  exportCar:key=>ipcRenderer.invoke('launcher:export-car',key),
  importCar:key=>ipcRenderer.invoke('launcher:import-car',key),
  exportAsset:index=>ipcRenderer.invoke('launcher:export-asset',index),
  replaceAsset:index=>ipcRenderer.invoke('launcher:replace-asset',index),
  saveMaterial:(id,key,properties,revision)=>ipcRenderer.invoke('launcher:save-material',id,key,properties,revision),
  publishMods:()=>ipcRenderer.invoke('launcher:publish-mods'),
  project:()=>ipcRenderer.invoke('launcher:project'),
  editProject:(changes,revision)=>ipcRenderer.invoke('launcher:edit-project',changes,revision),
  editProjectSelection:(selected,revision)=>ipcRenderer.invoke('launcher:edit-project-selection',selected,revision),
  projectHistory:(direction,revision)=>ipcRenderer.invoke('launcher:project-history',direction,revision),
  saveProject:revision=>ipcRenderer.invoke('launcher:save-project',revision),
  applyProject:revision=>ipcRenderer.invoke('launcher:apply-project',revision),
  importMod:()=>ipcRenderer.invoke('launcher:import-mod'),
  saveModDetails:(id,details)=>ipcRenderer.invoke('launcher:save-mod-details',id,details),
  toggleMod:(id,enabled)=>ipcRenderer.invoke('launcher:toggle-mod',id,enabled),
  resolveConflict:(key,winner)=>ipcRenderer.invoke('launcher:resolve-conflict',key,winner),
  removeMod:id=>ipcRenderer.invoke('launcher:remove-mod',id),
  exportMod:id=>ipcRenderer.invoke('launcher:export-mod',id),
  onState:listener=>{const fn=(_event,state)=>listener(state);ipcRenderer.on('launcher:state',fn);return()=>ipcRenderer.removeListener('launcher:state',fn);}
}));
